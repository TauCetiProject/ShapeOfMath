const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1280,height:960}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:8000/experiments/2015/overlap');
  await page.locator('.chart').first().waitFor();
  assert.equal(await page.locator('.chart').count(),4);
  assert.equal(await page.locator('#summary tr').count(),4);
  assert.match(await page.locator('#summary').innerText(),/1,166/);
  assert.match(await page.locator('#scope-note').innerText(),/reviewed/);
  await page.locator('circle[data-group="combined"][data-n="29"]').focus();
  assert.match(await page.locator('#point-detail').innerText(),/27\.9/);
  await page.locator('#example').check();
  await page.locator('circle[data-group="combined"][data-n="0"]').hover();
  assert.match(await page.locator('#point-detail').innerText(),/Example 1:/);
  await page.locator('#order').selectOption({value:'3'});
  await page.locator('circle[data-group="combined"][data-n="0"]').focus();
  assert.match(await page.locator('#point-detail').innerText(),/Example 4:/);
  await page.locator('#metric').selectOption('cumulative');
  await page.locator('circle[data-group="combined"][data-n="29"]').focus();
  assert.match(await page.locator('#point-detail').innerText(),/1,166/);
  await page.locator('#scope').selectOption('all_linked');
  assert.match(await page.locator('#scope-note').innerText(),/106/);
  assert.match(await page.locator('#summary').innerText(),/1,294/);
  await page.locator('#scope').selectOption('reading_introduced');
  assert.match(await page.locator('#scope-note').innerText(),/65/);
  await page.locator('#group').selectOption('math.NT');
  assert.equal(await page.locator('.chart').count(),1);
  assert.equal(await page.locator('#summary tr').count(),1);
  await page.reload();await page.locator('.chart').first().waitFor();
  assert.equal(await page.locator('#scope').inputValue(),'reading_introduced');
  assert.equal(await page.locator('#group').inputValue(),'math.NT');
  const paths=await page.locator('a[href^="/experiments/"]').evaluateAll(as=>as.map(a=>a.getAttribute('href')));
  for(const path of new Set(paths)){
    const response=await page.request.get('http://localhost:8000'+path);assert.equal(response.status(),200,path);
  }
  const privateResponse=await page.request.get('http://localhost:8000/experiments/curation-2015/overlap/analyse.py');
  assert.equal(privateResponse.status(),404);
  await page.locator('#scope').selectOption('reading');
  await page.locator('#group').selectOption('all');
  await page.locator('#metric').selectOption('marginal');
  await page.screenshot({path:'/tmp/shape-math-browser/overlap-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.screenshot({path:'/tmp/shape-math-browser/overlap-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('Overlap viewer: all pools/scopes, exact endpoint values, example order, URL state, downloads, allowlist and mobile pass.');
})().catch(error=>{console.error(error);process.exit(1);});
