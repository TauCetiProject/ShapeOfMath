def main():
    inventory=json.loads((ROOT/'archive/before-full-data-review/inventory.json').read_text())
    active={r['slug']:r for r in inventory['concept'] if r['status']=='active'}
    assert set(REVISIONS)|set(PARENTS)|set(GAPS)|set(NOTES) <= active.keys()
    # Finiteness here concerns the child sets, not the whole vertex set.
    plan={
      'baseline':'Sets, natural numbers, elementary logic and finite arithmetic; no arbitrary advanced primitive vocabulary.',
      'inventory':'archive/before-full-data-review/inventory.json',
      'revisions':REVISIONS,
      'parents':{k:v.split() for k,v in PARENTS.items()},
      'concepts':[{ 'slug':s, 'definition':'revise' if s in REVISIONS else 'retain',
                    'review_note':NOTES.get(s,'Retain the stated mathematical identity, hypotheses and paragraph; immediate parents reviewed against this definition or the annotated proof route.'),
                    'prerequisites_complete':s not in GAPS,
                    'missing_prerequisites':GAPS.get(s,[]) }
                  for s in active],
    }
    (ROOT/'data/full-review-plan.json').write_text(json.dumps(plan,ensure_ascii=False,indent=2)+'\n')
    print(f'{len(active)} concept decisions; {len(REVISIONS)} revisions; {len(GAPS)} open immediate lists')

if __name__=='__main__':main()
