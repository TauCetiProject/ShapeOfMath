-- PostgreSQL schema equivalent to schema.sql version 10.
--
-- Keep the two files in step. Differences from SQLite:
-- * Integer primary keys are identity columns; boolean flags stay 0/1 integers.
-- * Each table event has one trigger function. Its checks run in the order SQLite
--   fires the corresponding triggers (most recently created first), so the same
--   error is reported when several checks fail.
-- * The cycle check walks prerequisites from the new prerequisite, which stays
--   small, instead of dependents from the new dependent, which for foundational
--   concepts is most of the collection. Both detect exactly the same cycles.
-- * Graph writes take the writer advisory lock (pgcompat.WRITER_LOCK), so
--   concurrent transactions cannot each add half of a cycle.

CREATE COLLATION IF NOT EXISTS nocase (provider = icu, locale = 'und-u-ks-level2', deterministic = false);

CREATE TABLE IF NOT EXISTS schema_version (version integer NOT NULL);
INSERT INTO schema_version SELECT 10 WHERE NOT EXISTS (SELECT 1 FROM schema_version);

CREATE TABLE IF NOT EXISTS concept (
    id TEXT PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL CHECK(length(trim(title)) BETWEEN 1 AND 200),
    kind TEXT NOT NULL CHECK(kind IN ('definition', 'theorem', 'construction', 'conjecture')),
    description TEXT NOT NULL CHECK(length(trim(description)) BETWEEN 1 AND 1500
        AND position(chr(10) in description) = 0 AND position(chr(13) in description) = 0),
    field TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active', 'superseded')),
    boundary INTEGER NOT NULL DEFAULT 0 CHECK(boundary IN (0, 1)),
    revision INTEGER NOT NULL DEFAULT 1 CHECK(revision > 0),
    prerequisites_complete INTEGER NOT NULL DEFAULT 0 CHECK(prerequisites_complete IN (0, 1)),
    statement_prerequisites_complete INTEGER NOT NULL DEFAULT 0 CHECK(statement_prerequisites_complete IN (0,1)),
    proof_prerequisites_complete INTEGER NOT NULL DEFAULT 0 CHECK(proof_prerequisites_complete IN (0,1))
);
CREATE TABLE IF NOT EXISTS concept_alias (
    concept_id TEXT NOT NULL REFERENCES concept(id),
    alias TEXT NOT NULL COLLATE nocase,
    PRIMARY KEY (concept_id, alias)
);
CREATE TABLE IF NOT EXISTS source (
    id TEXT PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    authors TEXT NOT NULL,
    year INTEGER,
    field TEXT NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('catalogued', 'draft', 'reviewed')),
    coverage TEXT NOT NULL,
    summary TEXT NOT NULL,
    dependency_review TEXT NOT NULL,
    requirements_complete INTEGER NOT NULL DEFAULT 0 CHECK(requirements_complete IN (0, 1)),
    introductions_complete INTEGER NOT NULL DEFAULT 0 CHECK(introductions_complete IN (0, 1)),
    citations_complete INTEGER NOT NULL DEFAULT 0 CHECK(citations_complete IN (0, 1))
);
CREATE TABLE IF NOT EXISTS source_identifier (
    scheme TEXT NOT NULL,
    value TEXT NOT NULL,
    source_id TEXT NOT NULL REFERENCES source(id),
    PRIMARY KEY (scheme, value)
);
CREATE INDEX IF NOT EXISTS source_identifier_source ON source_identifier(source_id);
-- A bibliography entry can exist before its referenced source is identified.
CREATE TABLE IF NOT EXISTS citation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id TEXT NOT NULL REFERENCES source(id),
    label TEXT CHECK(label IS NULL OR length(trim(label)) > 0),
    text TEXT NOT NULL CHECK(length(trim(text)) > 0),
    cited_source_id TEXT REFERENCES source(id),
    pedagogically_necessary INTEGER CHECK(pedagogically_necessary IN (0,1)),
    needed_material TEXT,
    UNIQUE(source_id, label)
);
CREATE INDEX IF NOT EXISTS citation_target ON citation(cited_source_id);
CREATE TABLE IF NOT EXISTS citation_identifier (
    citation_id BIGINT NOT NULL REFERENCES citation(id) ON DELETE CASCADE,
    scheme TEXT NOT NULL,
    value TEXT NOT NULL,
    PRIMARY KEY(citation_id, scheme, value)
);
CREATE TABLE IF NOT EXISTS source_artifact (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id TEXT NOT NULL REFERENCES source(id),
    url TEXT NOT NULL,
    version TEXT NOT NULL DEFAULT '',
    accessed_at TEXT NOT NULL,
    sha256 TEXT,
    local_path TEXT,
    note TEXT NOT NULL,
    UNIQUE(source_id, url, version)
);
-- Direction is ALWAYS prerequisite -> dependent.
CREATE TABLE IF NOT EXISTS concept_dependency (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prerequisite_id TEXT NOT NULL REFERENCES concept(id),
    dependent_id TEXT NOT NULL REFERENCES concept(id),
    basis TEXT NOT NULL CHECK(basis IN ('logical', 'pedagogical', 'both')),
    rationale TEXT NOT NULL CHECK(length(trim(rationale)) > 0),
    evidence_source_id TEXT REFERENCES source(id),
    locator TEXT,
    purpose TEXT NOT NULL DEFAULT 'unclassified' CHECK(purpose IN ('statement','proof','both','unclassified')),
    CHECK(prerequisite_id <> dependent_id),
    UNIQUE(prerequisite_id, dependent_id)
);
CREATE INDEX IF NOT EXISTS concept_dependency_reverse ON concept_dependency(dependent_id);
CREATE TABLE IF NOT EXISTS source_concept (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id TEXT NOT NULL REFERENCES source(id),
    concept_id TEXT NOT NULL REFERENCES concept(id),
    role TEXT NOT NULL CHECK(role IN ('relies_on', 'introduces', 'explains', 'discusses')),
    locator TEXT NOT NULL CHECK(length(trim(locator)) > 0),
    note TEXT NOT NULL,
    introduction_evidence TEXT NOT NULL DEFAULT '',
    CHECK(role <> 'introduces' OR length(trim(introduction_evidence)) > 0),
    UNIQUE(source_id, concept_id, role, locator)
);
CREATE INDEX IF NOT EXISTS source_concept_concept ON source_concept(concept_id);
-- Canonical ordering makes this an undirected relation, separate from the DAG.
CREATE TABLE IF NOT EXISTS concept_related (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_a_id TEXT NOT NULL REFERENCES concept(id),
    concept_b_id TEXT NOT NULL REFERENCES concept(id),
    rationale TEXT NOT NULL CHECK(length(trim(rationale)) > 0),
    evidence_source_id TEXT REFERENCES source(id),
    locator TEXT,
    CHECK(concept_a_id < concept_b_id),
    UNIQUE(concept_a_id, concept_b_id)
);
CREATE INDEX IF NOT EXISTS concept_related_reverse ON concept_related(concept_b_id);
-- A citation is not a strict dependency. Store reviewed examples of both.
CREATE TABLE IF NOT EXISTS source_relation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dependent_id TEXT NOT NULL REFERENCES source(id),
    prerequisite_id TEXT NOT NULL REFERENCES source(id),
    kind TEXT NOT NULL CHECK(kind IN ('citation', 'historical', 'strict_dependency')),
    fact TEXT NOT NULL,
    locator TEXT NOT NULL,
    rationale TEXT NOT NULL,
    general_availability TEXT NOT NULL,
    UNIQUE(dependent_id, prerequisite_id, kind, fact),
    CHECK(dependent_id <> prerequisite_id),
    CHECK(kind <> 'strict_dependency' OR
          (length(trim(fact)) > 0 AND length(trim(locator)) > 0 AND
           length(trim(rationale)) > 0 AND length(trim(general_availability)) > 0))
);
CREATE TABLE IF NOT EXISTS embedding_model (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    artifact_sha256 TEXT NOT NULL,
    dimensions INTEGER NOT NULL,
    configuration TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS concept_embedding (
    concept_id TEXT NOT NULL REFERENCES concept(id),
    model_id TEXT NOT NULL REFERENCES embedding_model(id),
    content_sha256 TEXT NOT NULL,
    vector BYTEA NOT NULL,
    PRIMARY KEY(concept_id, model_id)
);
CREATE TABLE IF NOT EXISTS curation_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    operation TEXT NOT NULL,
    reason TEXT NOT NULL,
    before_json TEXT NOT NULL,
    after_json TEXT NOT NULL
);

CREATE OR REPLACE VIEW active_source_concept AS
SELECT si.* FROM source_concept si JOIN concept i ON i.id = si.concept_id WHERE i.status = 'active';
CREATE OR REPLACE VIEW strict_source_dependency AS
SELECT * FROM source_relation WHERE kind = 'strict_dependency';

-- Libraries are extensible; file paths are relative to each repository root.
CREATE TABLE IF NOT EXISTS formalization_library (
    slug TEXT PRIMARY KEY CHECK(length(trim(slug)) > 0),
    name TEXT NOT NULL CHECK(length(trim(name)) > 0),
    repository_url TEXT
);
INSERT INTO formalization_library(slug,name) VALUES ('mathlib','Mathlib') ON CONFLICT DO NOTHING;
INSERT INTO formalization_library(slug,name) VALUES ('tau-ceti','Tau Ceti') ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS formalization_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_slug TEXT NOT NULL REFERENCES formalization_library(slug),
    path TEXT NOT NULL CHECK(length(trim(path)) > 0),
    loc INTEGER CHECK(loc IS NULL OR loc >= 0),
    revision TEXT,
    measured_at TEXT,
    sha256 TEXT,
    UNIQUE(library_slug,path),
    CHECK((loc IS NULL AND revision IS NULL AND measured_at IS NULL AND sha256 IS NULL)
        OR (loc IS NOT NULL AND length(trim(revision)) > 0 AND revision IS NOT NULL
            AND length(trim(measured_at)) > 0 AND measured_at IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS concept_formalization (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_id TEXT NOT NULL REFERENCES concept(id),
    library_slug TEXT NOT NULL REFERENCES formalization_library(slug),
    status TEXT NOT NULL CHECK(status IN ('formalized','partial','inherited','not_formalized','unknown')),
    evidence TEXT NOT NULL CHECK(length(trim(evidence)) > 0),
    concept_revision INTEGER NOT NULL CHECK(concept_revision > 0),
    reviewed_at TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    UNIQUE(concept_id,library_slug)
);
CREATE TABLE IF NOT EXISTS concept_formalization_file (
    formalization_id BIGINT NOT NULL REFERENCES concept_formalization(id) ON DELETE CASCADE,
    file_id BIGINT NOT NULL REFERENCES formalization_file(id),
    declarations TEXT NOT NULL DEFAULT '',
    note TEXT NOT NULL CHECK(length(trim(note)) > 0),
    PRIMARY KEY(formalization_id,file_id)
);

-- Only current reviews of active concepts share a file. Partial implementations
-- participate too: their files implement part of that concept, and consume a share.
CREATE OR REPLACE VIEW formalization_file_allocation AS
SELECT f.*, count(*) AS mapped_concepts, f.loc::double precision/count(*) AS allocated_loc
FROM formalization_file f
JOIN concept_formalization_file link ON link.file_id=f.id
JOIN concept_formalization cf ON cf.id=link.formalization_id
JOIN concept c ON c.id=cf.concept_id
WHERE c.status='active' AND c.revision=cf.concept_revision AND cf.status IN ('formalized','partial')
GROUP BY f.id;

CREATE OR REPLACE VIEW concept_formalization_loc AS
SELECT cf.id AS formalization_id, cf.concept_id, cf.library_slug,
    count(*) AS file_count, count(a.loc) AS measured_files,
    coalesce(sum(a.allocated_loc),0.0) AS known_loc,
    CASE WHEN count(*)=count(a.loc) THEN sum(a.allocated_loc) END AS estimated_loc
FROM concept_formalization cf
JOIN concept c ON c.id=cf.concept_id
JOIN concept_formalization_file link ON link.formalization_id=cf.id
JOIN formalization_file_allocation a ON a.id=link.file_id
WHERE c.status='active' AND c.revision=cf.concept_revision AND cf.status IN ('formalized','partial')
GROUP BY cf.id;

-- ---------------------------------------------------------------------------
-- concept_dependency: checks before insert/update, review flags after.

CREATE OR REPLACE FUNCTION concept_dependency_check() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(7307102);
    IF EXISTS (SELECT 1 FROM concept WHERE id IN (NEW.prerequisite_id, NEW.dependent_id) AND status <> 'active') THEN
        RAISE EXCEPTION 'dependency endpoint is superseded' USING ERRCODE = 'P0001';
    END IF;
    -- p -> d closes a cycle exactly when d is already in the prerequisite cone of p.
    IF EXISTS (
        WITH RECURSIVE cone(id) AS (
            SELECT NEW.prerequisite_id
            UNION
            SELECT d.prerequisite_id FROM concept_dependency d JOIN cone ON d.dependent_id = cone.id
            WHERE TG_OP = 'INSERT' OR d.id <> OLD.id
        ) SELECT 1 FROM cone WHERE id = NEW.dependent_id
    ) THEN
        RAISE EXCEPTION 'concept dependency would create a cycle' USING ERRCODE = 'P0001';
    END IF;
    IF NEW.purpose IN ('proof','both')
       AND (SELECT kind FROM concept WHERE id = NEW.dependent_id) NOT IN ('theorem','conjecture') THEN
        RAISE EXCEPTION 'proof prerequisites target theorem-shaped concepts' USING ERRCODE = 'P0001';
    END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER concept_dependency_check BEFORE INSERT OR UPDATE ON concept_dependency
    FOR EACH ROW EXECUTE FUNCTION concept_dependency_check();

-- Completion is a local review judgment, never inferred from graph traversal.
CREATE OR REPLACE FUNCTION concept_dependency_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE concept SET prerequisites_complete=0,
            statement_prerequisites_complete=CASE WHEN NEW.purpose='proof' THEN statement_prerequisites_complete ELSE 0 END,
            proof_prerequisites_complete=0 WHERE id=NEW.dependent_id;
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        UPDATE concept SET prerequisites_complete=0,
            statement_prerequisites_complete=CASE WHEN OLD.purpose='proof' THEN statement_prerequisites_complete ELSE 0 END,
            proof_prerequisites_complete=0 WHERE id=OLD.dependent_id;
        RETURN OLD;
    END IF;
    UPDATE concept SET prerequisites_complete=0,
        statement_prerequisites_complete=CASE
            WHEN OLD.purpose='proof' AND NEW.purpose='proof' THEN statement_prerequisites_complete
            WHEN OLD.prerequisite_id=NEW.prerequisite_id AND OLD.dependent_id=NEW.dependent_id
                AND OLD.purpose IN ('statement','both') AND NEW.purpose IN ('statement','both')
                AND OLD.purpose<>NEW.purpose THEN statement_prerequisites_complete
            ELSE 0 END,
        proof_prerequisites_complete=0
        WHERE id IN (OLD.dependent_id,NEW.dependent_id);
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER concept_dependency_changed AFTER INSERT OR UPDATE OR DELETE ON concept_dependency
    FOR EACH ROW EXECUTE FUNCTION concept_dependency_changed();

-- ---------------------------------------------------------------------------
-- concept: checks before update, revision bump, review flags after.

CREATE OR REPLACE FUNCTION concept_update_check() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status = 'superseded' THEN
        IF EXISTS (SELECT 1 FROM concept_related WHERE concept_a_id=OLD.id OR concept_b_id=OLD.id) THEN
            RAISE EXCEPTION 'reroute related links before superseding a concept' USING ERRCODE = 'P0001';
        END IF;
        IF EXISTS (SELECT 1 FROM concept_dependency WHERE prerequisite_id = OLD.id OR dependent_id = OLD.id) THEN
            RAISE EXCEPTION 'reroute dependencies before superseding an concept' USING ERRCODE = 'P0001';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER concept_status_check BEFORE UPDATE OF status ON concept
    FOR EACH ROW EXECUTE FUNCTION concept_update_check();

CREATE OR REPLACE FUNCTION concept_kind_check() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.kind NOT IN ('theorem','conjecture') AND EXISTS(
        SELECT 1 FROM concept_dependency WHERE dependent_id=NEW.id AND purpose IN ('proof','both')) THEN
        RAISE EXCEPTION 'reclassify proof prerequisites before changing theorem kind' USING ERRCODE = 'P0001';
    END IF;
    RETURN NEW;
END $$;
-- Named so it sorts after concept_status_check, matching SQLite's firing order.
CREATE OR REPLACE TRIGGER concept_update_kind_check BEFORE UPDATE OF kind ON concept
    FOR EACH ROW EXECUTE FUNCTION concept_kind_check();

CREATE OR REPLACE FUNCTION concept_revision_bump() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.revision := OLD.revision + 1;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER concept_update_revision BEFORE UPDATE OF title, kind, description ON concept
    FOR EACH ROW EXECUTE FUNCTION concept_revision_bump();

CREATE OR REPLACE FUNCTION concept_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.title IS DISTINCT FROM NEW.title OR OLD.kind IS DISTINCT FROM NEW.kind
       OR OLD.description IS DISTINCT FROM NEW.description OR OLD.status IS DISTINCT FROM NEW.status THEN
        UPDATE concept SET prerequisites_complete=0,statement_prerequisites_complete=0,proof_prerequisites_complete=0 WHERE id=NEW.id OR id IN (
            SELECT dependent_id FROM concept_dependency WHERE prerequisite_id=NEW.id);
        UPDATE source SET requirements_complete=0 WHERE id IN (
            SELECT source_id FROM source_concept WHERE concept_id=NEW.id AND role='relies_on');
        UPDATE source SET introductions_complete=0 WHERE id IN (
            SELECT source_id FROM source_concept WHERE concept_id=NEW.id AND role='introduces');
    END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER concept_changed_review AFTER UPDATE OF title,kind,description,status ON concept
    FOR EACH ROW EXECUTE FUNCTION concept_changed();

CREATE OR REPLACE FUNCTION concept_embedding_invalidate() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM concept_embedding WHERE concept_id = NEW.id;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER invalidate_embedding AFTER UPDATE OF title, kind, description ON concept
    FOR EACH ROW EXECUTE FUNCTION concept_embedding_invalidate();

-- ---------------------------------------------------------------------------
-- concept_related

CREATE OR REPLACE FUNCTION concept_related_check() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM concept WHERE id IN (NEW.concept_a_id,NEW.concept_b_id) AND status <> 'active') THEN
        RAISE EXCEPTION 'related endpoint is superseded' USING ERRCODE = 'P0001';
    END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER related_active BEFORE INSERT OR UPDATE ON concept_related
    FOR EACH ROW EXECUTE FUNCTION concept_related_check();

-- ---------------------------------------------------------------------------
-- source review flags

CREATE OR REPLACE FUNCTION source_coverage_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.coverage IS DISTINCT FROM OLD.coverage THEN
        UPDATE source SET requirements_complete=0,introductions_complete=0,citations_complete=0 WHERE id=NEW.id;
    END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER source_coverage_changed AFTER UPDATE OF coverage ON source
    FOR EACH ROW EXECUTE FUNCTION source_coverage_changed();

CREATE OR REPLACE FUNCTION source_concept_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND NOT (OLD.source_id IS DISTINCT FROM NEW.source_id OR OLD.concept_id IS DISTINCT FROM NEW.concept_id
            OR OLD.role IS DISTINCT FROM NEW.role OR OLD.introduction_evidence IS DISTINCT FROM NEW.introduction_evidence) THEN
        RETURN NEW;
    END IF;
    IF TG_OP IN ('UPDATE','DELETE') THEN
        UPDATE source SET requirements_complete=0 WHERE id=OLD.source_id AND OLD.role='relies_on';
        UPDATE source SET introductions_complete=0 WHERE id=OLD.source_id AND OLD.role='introduces';
    END IF;
    IF TG_OP IN ('UPDATE','INSERT') THEN
        UPDATE source SET requirements_complete=0 WHERE id=NEW.source_id AND NEW.role='relies_on';
        UPDATE source SET introductions_complete=0 WHERE id=NEW.source_id AND NEW.role='introduces';
        RETURN NEW;
    END IF;
    RETURN OLD;
END $$;
CREATE OR REPLACE TRIGGER source_concepts_changed AFTER INSERT OR UPDATE OR DELETE ON source_concept
    FOR EACH ROW EXECUTE FUNCTION source_concept_changed();

CREATE OR REPLACE FUNCTION source_artifact_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP IN ('UPDATE','DELETE') THEN
        UPDATE source SET requirements_complete=0,introductions_complete=0,citations_complete=0 WHERE id=OLD.source_id;
    END IF;
    IF TG_OP IN ('UPDATE','INSERT') THEN
        UPDATE source SET requirements_complete=0,introductions_complete=0,citations_complete=0 WHERE id=NEW.source_id;
        RETURN NEW;
    END IF;
    RETURN OLD;
END $$;
CREATE OR REPLACE TRIGGER source_artifact_changed AFTER INSERT OR UPDATE OR DELETE ON source_artifact
    FOR EACH ROW EXECUTE FUNCTION source_artifact_changed();

-- Capturing bibliography entries is independent of resolving or assessing them.
CREATE OR REPLACE FUNCTION citation_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE source SET citations_complete=0 WHERE id=NEW.source_id;
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        UPDATE source SET citations_complete=0 WHERE id=OLD.source_id;
        RETURN OLD;
    END IF;
    IF OLD.source_id IS DISTINCT FROM NEW.source_id OR OLD.label IS DISTINCT FROM NEW.label OR OLD.text IS DISTINCT FROM NEW.text THEN
        UPDATE source SET citations_complete=0 WHERE id IN (OLD.source_id,NEW.source_id);
    END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER citation_changed AFTER INSERT OR DELETE OR UPDATE OF source_id,label,text ON citation
    FOR EACH ROW EXECUTE FUNCTION citation_changed();

-- ---------------------------------------------------------------------------
-- formalization files must belong to the reviewed library

CREATE OR REPLACE FUNCTION formalization_file_library_check() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT library_slug FROM concept_formalization WHERE id=NEW.formalization_id) <>
       (SELECT library_slug FROM formalization_file WHERE id=NEW.file_id) THEN
        RAISE EXCEPTION 'formalization file belongs to a different library' USING ERRCODE = 'P0001';
    END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER formalization_file_library BEFORE INSERT OR UPDATE ON concept_formalization_file
    FOR EACH ROW EXECUTE FUNCTION formalization_file_library_check();
